-- ── ROW LEVEL SECURITY ──────────────────────────────────────────────────────
-- The Express server will use the SECRET key, which bypasses RLS entirely.
-- These policies only govern direct client-side (publishable key) access.

alter table public.products         enable row level security;
alter table public.orders           enable row level security;
alter table public.contact_messages enable row level security;
alter table public.promo_codes      enable row level security;

-- Anyone can browse non-archived products (shop + product pages)
create policy "Public read active products"
    on public.products for select
    using (archived = false);

-- Anyone can read active promo codes (checkout coupon validation)
create policy "Public read active promo codes"
    on public.promo_codes for select
    using (active = true);

-- Anyone can submit a contact message; reading them stays server-only
create policy "Anyone can submit contact message"
    on public.contact_messages for insert
    with check (true);

-- Orders: NO public policies. Anonymous users cannot read other people's
-- orders, and cannot create/modify them directly. All order reads/writes go
-- through your server (secret key). If you later move checkout fully
-- client-side, add e.g.:
--   create policy "Anyone can create an order"
--       on public.orders for insert with check (true);

